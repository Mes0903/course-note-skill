#!/usr/bin/env bash
set -euo pipefail

COURSE_NOTES_RUNTIME_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd -P)"
COURSE_NOTES_REPO_ROOT="$(cd -- "$COURSE_NOTES_RUNTIME_DIR/../.." && pwd -P)"
COURSE_NOTES_DENO_DIR="$COURSE_NOTES_REPO_ROOT/.tools/deno"
COURSE_NOTES_CUBLAS_LIBRARY="$COURSE_NOTES_REPO_ROOT/.venv/lib/python3.12/site-packages/nvidia/cublas/lib"
COURSE_NOTES_CUDNN_LIBRARY="$COURSE_NOTES_REPO_ROOT/.venv/lib/python3.12/site-packages/nvidia/cudnn/lib"

PATH="$COURSE_NOTES_DENO_DIR:$PATH"
export PATH

COURSE_NOTES_LIBRARIES=()
[[ -d "$COURSE_NOTES_CUBLAS_LIBRARY" ]] && COURSE_NOTES_LIBRARIES+=("$COURSE_NOTES_CUBLAS_LIBRARY")
[[ -d "$COURSE_NOTES_CUDNN_LIBRARY" ]] && COURSE_NOTES_LIBRARIES+=("$COURSE_NOTES_CUDNN_LIBRARY")
if ((${#COURSE_NOTES_LIBRARIES[@]})); then
  COURSE_NOTES_JOINED="$(IFS=:; echo "${COURSE_NOTES_LIBRARIES[*]}")"
  LD_LIBRARY_PATH="${COURSE_NOTES_JOINED}${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}"
  export LD_LIBRARY_PATH
fi

unset COURSE_NOTES_RUNTIME_DIR COURSE_NOTES_DENO_DIR
unset COURSE_NOTES_CUBLAS_LIBRARY COURSE_NOTES_CUDNN_LIBRARY
unset COURSE_NOTES_LIBRARIES COURSE_NOTES_JOINED
